"""Evaluation logging and telemetry audit utilities for anti-spoofing decisions."""

import json
import logging
from pathlib import Path
import time
from typing import Any, Dict, Optional

from app.core.config import settings
from app.liveness.base import LivenessResult

logger = logging.getLogger("app.liveness.audit")


class LivenessEvaluator:
    """Records and analyzes liveness evaluation decisions for empirical validation."""

    def __init__(self, log_path: Optional[str] = None):
        """Initialize evaluator with an optional audit log destination."""
        self.log_path = Path(log_path or settings.LIVENESS_LOG_PATH)
        self.enabled = settings.LIVENESS_LOG_EVALUATIONS
        self._ensure_log_directory()

    def _ensure_log_directory(self) -> None:
        """Ensure parent directory exists for file-based audit logging."""
        if self.enabled:
            try:
                self.log_path.parent.mkdir(parents=True, exist_ok=True)
            except Exception as exc:
                logger.warning("Could not create audit log directory '%s': %s", self.log_path.parent, exc)

    def log_evaluation(
        self,
        result: LivenessResult,
        track_id: Optional[int] = None,
        student_id: Optional[str] = None,
        session_id: Optional[str] = None,
        extra_metadata: Optional[Dict[str, Any]] = None,
    ) -> None:
        """Log a structured audit record of a liveness evaluation event.
        
        Args:
            result: LivenessResult generated by a detector.
            track_id: Face tracking sequence identifier.
            student_id: Claimed or matched student ID if available.
            session_id: Active class attendance session ID.
            extra_metadata: Additional context dictionary.
        """
        if not self.enabled:
            return

        record = {
            "timestamp": time.time(),
            "is_live": result.is_live,
            "score": round(float(result.score), 4),
            "status": result.status.value,
            "reason": result.reason,
            "track_id": track_id,
            "student_id": student_id,
            "session_id": session_id,
            "cues": result.cues,
            "active_challenge": result.active_challenge.value if result.active_challenge else None,
            "metadata": extra_metadata or {},
        }

        # 1. Log to standard Python logger
        if result.is_live:
            logger.debug(
                "Liveness PASSED [Track #%s | Student: %s]: score=%.3f, reason=%s",
                track_id,
                student_id,
                result.score,
                result.reason,
            )
        else:
            logger.warning(
                "Liveness ALERT [Track #%s | Student: %s]: status=%s, score=%.3f, reason=%s",
                track_id,
                student_id,
                result.status.value,
                result.score,
                result.reason,
            )

        # 2. Append JSON line to audit file for offline analysis and evaluation
        try:
            with open(self.log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(record) + "\n")
        except Exception as exc:
            logger.debug("Failed writing to liveness audit file '%s': %s", self.log_path, exc)


# Global default evaluator instance
_evaluator: Optional[LivenessEvaluator] = None


def get_liveness_evaluator() -> LivenessEvaluator:
    """Return singleton instance of LivenessEvaluator."""
    global _evaluator
    if _evaluator is None:
        _evaluator = LivenessEvaluator()
    return _evaluator
